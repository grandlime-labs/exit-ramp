// Inlines templates/*.ts into src/core/templates.generated.ts so core has no filesystem access
// (it must run in a browser). Run: node scripts/gen-templates.mjs   (npm run gen)
// `--check` exits 1 if the committed file is out of date.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "templates");
const out = join(root, "src/core/templates.generated.ts");

const names = readdirSync(dir).filter((f) => f.endsWith(".ts")).sort();
let body = "// GENERATED by scripts/gen-templates.mjs from templates/*.ts. Do not edit; run `npm run gen`.\n\n";
body += "export const TEMPLATES: Record<string, string> = {\n";
for (const n of names) body += `  ${JSON.stringify(n.replace(/\.ts$/, ""))}: ${JSON.stringify(readFileSync(join(dir, n), "utf8"))},\n`;
body += "};\n";

if (process.argv.includes("--check")) {
  const cur = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (cur !== body) {
    console.error("templates.generated.ts is out of date. Run: npm run gen");
    process.exit(1);
  }
  console.log("templates.generated.ts is up to date");
} else {
  writeFileSync(out, body);
  console.log(`wrote ${out} (${names.length} templates)`);
}
