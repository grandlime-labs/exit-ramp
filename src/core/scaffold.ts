export const DEFAULT_COMPAT_DATE = "2026-10-01";

export interface ScaffoldInput {
  target: Target;
  projectName: string;
  compatibilityDate: string;
  analyses: FileAnalysis[];
  dependencies: Dependency[];
  bindings: Bindings;
  /** extra non-fatal notes appended to the report (multiple entry points etc.) */
  warnings: string[];
}

export function slugify(name: string): string {
  const s = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return (s || "exit-ramp-app").slice(0, 54);
}

const tomlStr = (s: string) => JSON.stringify(s);

function stripExt(p: string): string {
  return p.replace(/\.(?:[cm]?[jt]sx?)$/, "");
}

function relFromSrc(outPath: string): string {
  return "./" + stripExt(outPath.replace(/^src\//, ""));
}

function entryKey(a: FileAnalysis): number {
  const base = a.path.split("/").pop()!.toLowerCase();
  return (/^(?:main|index|app|server)\b/.test(base) ? 0 : 1) * 1000 + a.path.split("/").length * 10 + (a.denoServe ? 0 : 1);
}

export function wranglerToml(i: ScaffoldInput): string {
  const b = i.bindings;
  const name = slugify(i.projectName);
  const L: string[] = [];
  L.push(`# Generated by exit-ramp. Review every TODO before \`wrangler deploy\`.`);
  L.push(`name = ${tomlStr(name)}`);
  L.push(`main = "src/worker.ts"`);
  L.push(`compatibility_date = ${tomlStr(i.compatibilityDate)}`);
  L.push(`compatibility_flags = ["nodejs_compat"]`);
  L.push(`# Local development needs no Cloudflare account: \`npm run dev\` runs workerd locally with simulated bindings.`);
  const known = [...new Set(b.cronSchedules.filter((c) => c.schedule).map((c) => c.schedule!))];
  const unknown = b.cronSchedules.filter((c) => !c.schedule);
  if (b.cronSchedules.length) {
    L.push("", "# Cron Triggers always run in UTC. Weekdays here are 1=SUN ... 7=SAT (Cloudflare numbering, not unix).");
    L.push("[triggers]");
    L.push(`crons = [${known.map(tomlStr).join(", ")}]`);
    for (const u of unknown) L.push(`# TODO(exit-ramp): ${u.file} is a cron job with no known schedule. Add its cron expression to the list above (UTC).`);
  }
  if (b.kv) {
    L.push("", "# Workers KV: eventually consistent. See MIGRATION_REPORT.md. Omit `id` and wrangler provisions the namespace on first deploy.", "[[kv_namespaces]]", `binding = "KV"`);
  }
  if (b.d1) {
    L.push("", "# D1 (SQLite). Create it, apply your schema and import data before cutting over.", "[[d1_databases]]", `binding = "DB"`, `database_name = ${tomlStr(name + "-db")}`);
  }
  if (b.r2) {
    L.push("", "[[r2_buckets]]", `binding = "BLOB"`, `bucket_name = ${tomlStr(name + "-blobs")}`);
  }
  if (b.email) {
    L.push("", "# Cloudflare Email Service sender. Needs an onboarded domain; see src/exit-ramp/email.ts.", "[[send_email]]", `name = "EMAIL"`);
  }
  if (b.envVars.length) {
    L.push("", "# Secrets/vars used by the code (set secrets with `wrangler secret put NAME`; local values go in .dev.vars):");
    for (const v of b.envVars) L.push(`#   ${v}`);
  }
  L.push("");
  return L.join("\n");
}

export function packageJson(i: ScaffoldInput): string {
  const deps: Record<string, string> = {};
  for (const d of i.dependencies) deps[d.name] = d.range;
  const workers = i.target === "workers";
  const pkg = workers
    ? {
        name: slugify(i.projectName),
        private: true,
        type: "module",
        scripts: { dev: "wrangler dev", deploy: "wrangler deploy", typecheck: "tsc --noEmit" },
        dependencies: sortObj(deps),
        devDependencies: { "@cloudflare/workers-types": "^5", typescript: "^7", wrangler: "^4" },
      }
    : {
        name: slugify(i.projectName),
        private: true,
        type: "module",
        scripts: { start: "tsx src/server.ts", typecheck: "tsc --noEmit" },
        dependencies: sortObj(deps),
        devDependencies: { "@types/node": "^22", tsx: "^4", typescript: "^7" },
      };
  return JSON.stringify(pkg, null, 2) + "\n";
}

function sortObj<T>(o: Record<string, T>): Record<string, T> {
  return Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
}

export function tsconfigJson(target: Target): string {
  const base = {
    target: "ES2022",
    module: "ES2022",
    moduleResolution: "bundler",
    lib: ["ES2022"],
    strict: true,
    noEmit: true,
    skipLibCheck: true,
    allowJs: true,
    checkJs: false,
    jsx: "react-jsx",
    isolatedModules: true,
    allowImportingTsExtensions: true,
    resolveJsonModule: true,
    types: target === "workers" ? ["@cloudflare/workers-types"] : ["node"],
  };
  return JSON.stringify({ compilerOptions: base, include: ["src"] }, null, 2) + "\n";
}

function envDts(i: ScaffoldInput): string {
  const b = i.bindings;
  const L: string[] = ["// Generated by exit-ramp. Types for the bindings and variables your code uses.", "declare namespace Cloudflare {", "  interface Env {"];
  if (b.kv) L.push("    KV: KVNamespace;");
  if (b.d1) L.push("    DB: D1Database;");
  if (b.r2) L.push("    BLOB: R2Bucket;");
  if (b.email) L.push("    EMAIL: SendEmail;", "    EXIT_RAMP_EMAIL_FROM?: string;", "    EXIT_RAMP_EMAIL_TO?: string;");
  for (const v of b.envVars) if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(v)) L.push(`    ${v}?: string;`);
  L.push("  }", "}", "");
  return L.join("\n");
}

function valtownTypesDts(b: Bindings): string {
  const L = ["// Generated by exit-ramp. Val Town provides these types globally; here they are declared once."];
  if (b.valtownTypes.interval) L.push("type Interval = { lastRunAt: Date | undefined };");
  if (b.valtownTypes.email) L.push('type Email = import("./exit-ramp/email-in").ValTownEmail;');
  L.push("");
  return L.join("\n");
}

export function devVarsExample(i: ScaffoldInput): string {
  const names = new Set(i.bindings.envVars);
  if (i.bindings.email) {
    names.add("EXIT_RAMP_EMAIL_FROM");
    names.add("EXIT_RAMP_EMAIL_TO");
  }
  return [`# Copy to ${i.target === "workers" ? ".dev.vars" : ".env"} and fill in. Never commit the real file.`, ...[...names].sort().map((n) => `${n}=`), ""].join("\n");
}

export function workerTs(i: ScaffoldInput): { text: string; warnings: string[] } {
  const warnings: string[] = [];
  const http = i.analyses.filter((a) => a.denoServe || a.entry?.type === "http").sort((a, b) => entryKey(a) - entryKey(b));
  const emails = i.analyses.filter((a) => a.entry?.type === "email").sort((a, b) => entryKey(a) - entryKey(b));
  const L: string[] = ["// Generated by exit-ramp: wires your converted modules to Workers entry points. Edit freely."];
  const mods = new Map<string, string>();
  const modOf = (a: FileAnalysis) => {
    if (!mods.has(a.path)) mods.set(a.path, `m${mods.size}`);
    return mods.get(a.path)!;
  };
  const body: string[] = [];
  const imports: string[] = [];

  type Job = { name: string; schedule: string | undefined; expr: string; uses?: boolean };
  const jobs: Job[] = [];
  for (const a of i.analyses) {
    if (a.entry?.type === "cron") {
      const m = modOf(a);
      const name = JSON.stringify(a.path);
      const sched = a.valCronSchedule ? JSON.stringify(a.valCronSchedule) : "undefined";
      if (a.entry.lastRunAt && i.target === "workers") {
        jobs.push({ name: a.path, schedule: a.valCronSchedule, expr: `{ name: ${name}, schedule: ${sched}, run: async (c: ScheduledController) => { const lastRunAt = await getLastRun(${name}); const r = await (${m}.default as unknown as (i: Interval) => unknown)({ lastRunAt }); await setLastRun(${name}, c.scheduledTime); return r; } }`, uses: true });
      } else {
        jobs.push({ name: a.path, schedule: a.valCronSchedule, expr: `{ name: ${name}, schedule: ${sched}, run: () => (${m}.default as unknown as (i: { lastRunAt: Date | undefined }) => unknown)({ lastRunAt: undefined }) }` });
      }
    }
    for (const c of a.denoCrons) {
      const m = modOf(a);
      jobs.push({ name: `${a.path}#${c.exportName}`, schedule: c.schedule, expr: `${m}.${c.exportName}` });
    }
  }

  const workers = i.target === "workers";
  if (workers) {
    const fetchEntry = http[0];
    if (http.length > 1) warnings.push(`Several HTTP entry points found (${http.map((h) => h.path).join(", ")}). A Worker has one fetch(): ${fetchEntry.path} is wired, the others are not. Merge them (for example with a router) by hand.`);
    if (emails.length > 1) warnings.push(`Several email vals found (${emails.map((h) => h.path).join(", ")}). Only ${emails[0].path} is wired to email(); route by recipient yourself.`);
    const hasEmail = emails.length > 0;
    const usesLast = jobs.some((j) => j.uses);
    const extra: string[] = [];
    if (fetchEntry) {
      const m = modOf(fetchEntry);
      imports.push(`import * as ${m} from ${JSON.stringify(relFromSrc(fetchEntry.outPath))};`);
      extra.push(
        "type Ctx = ExecutionContext;",
        fetchEntry.denoServe
          ? ""
          : `type HttpHandler = ((req: Request, env: Cloudflare.Env, ctx: Ctx) => Response | Promise<Response>) | { fetch(req: Request, env: Cloudflare.Env, ctx: Ctx): Response | Promise<Response> };`,
      );
      if (fetchEntry.denoServe) {
        extra.push(`type ServeInfo = { remoteAddr: { transport: "tcp"; hostname: string; port: number } };`);
        body.push(
          `  async fetch(request: Request, env: Cloudflare.Env, ctx: ExecutionContext): Promise<Response> {`,
          `    const info: ServeInfo = { remoteAddr: { transport: "tcp", hostname: request.headers.get("cf-connecting-ip") ?? "0.0.0.0", port: 0 } };`,
          `    return (${m}.exitRampFetch as unknown as (r: Request, info: ServeInfo) => Response | Promise<Response>)(request, info);`,
          `  },`,
        );
      } else {
        body.push(
          `  async fetch(request: Request, env: Cloudflare.Env, ctx: ExecutionContext): Promise<Response> {`,
          `    const h = ${m}.default as unknown as HttpHandler;`,
          `    return typeof h === "function" ? h(request, env, ctx) : h.fetch(request, env, ctx);`,
          `  },`,
        );
      }
    }
    if (jobs.length) {
      for (const a of i.analyses) if (a.entry?.type === "cron" || a.denoCrons.length) imports.push(`import * as ${modOf(a)} from ${JSON.stringify(relFromSrc(a.outPath))};`);
      if (usesLast) imports.push(`import { getLastRun, setLastRun } from "./exit-ramp/last-run";`);
      extra.push(
        `type Job = { name: string; schedule: string | undefined; run: (c: ScheduledController) => unknown };`,
        `const jobs: Job[] = [`,
        ...jobs.map((j) => `  ${j.expr},`),
        `];`,
      );
      body.push(
        `  async scheduled(controller: ScheduledController, env: Cloudflare.Env, ctx: ExecutionContext): Promise<void> {`,
        `    // Jobs are matched on the cron expression that fired. A single job always runs.`,
        `    const matching = jobs.filter((j) => j.schedule === controller.cron);`,
        `    const toRun = matching.length ? matching : jobs.length === 1 ? jobs : [];`,
        `    if (!toRun.length) console.warn(\`No job registered for cron "\${controller.cron}"\`);`,
        `    await Promise.all(toRun.map((j) => j.run(controller)));`,
        `  },`,
      );
    }
    if (hasEmail) {
      const e = emails[0];
      const m = modOf(e);
      if (!imports.some((x) => x.startsWith(`import * as ${m} `))) imports.push(`import * as ${m} from ${JSON.stringify(relFromSrc(e.outPath))};`);
      imports.push(`import { toValTownEmail } from "./exit-ramp/email-in";`);
      body.push(
        `  async email(message: ForwardableEmailMessage, env: Cloudflare.Env, ctx: ExecutionContext): Promise<void> {`,
        `    await (${m}.default as unknown as (e: Email) => unknown)(await toValTownEmail(message));`,
        `  },`,
      );
    }
    // dedupe imports, put module imports first
    const uniq = [...new Set(imports)];
    L.push(...uniq, "", ...extra.filter(Boolean), "", "export default {", ...body, "} satisfies ExportedHandler<Cloudflare.Env>;", "");
    if (!body.length) L.push("// No entry points were detected. Export a fetch(), scheduled() or email() handler above.", "");
    return { text: L.join("\n"), warnings };
  }

  // ---------- node target ----------
  const fetchEntry = http[0];
  if (http.length > 1) warnings.push(`Several HTTP entry points found (${http.map((h) => h.path).join(", ")}). Only ${fetchEntry.path} is served.`);
  L.push(`import { createServer } from "node:http";`, `import { Readable } from "node:stream";`);
  if (jobs.length) L.push(`import { Cron } from "croner";`);
  for (const a of i.analyses) if (a === fetchEntry || a.entry?.type === "cron" || a.denoCrons.length) L.push(`import * as ${modOf(a)} from ${JSON.stringify(relFromSrc(a.outPath))};`);
  L.push("");
  if (fetchEntry) {
    const m = modOf(fetchEntry);
    L.push(
      `type Handler = ((req: Request, info: unknown) => Response | Promise<Response>) | { fetch(req: Request): Response | Promise<Response> };`,
      `const handler = (${fetchEntry.denoServe ? `${m}.exitRampFetch` : `${m}.default`} as unknown) as Handler;`,
      `const port = Number(process.env.PORT ?? 8000);`,
      ``,
      `createServer(async (req, res) => {`,
      `  try {`,
      `    const url = new URL(req.url ?? "/", \`http://\${req.headers.host ?? "localhost"}\`);`,
      `    const headers = new Headers();`,
      `    for (const [k, v] of Object.entries(req.headers)) if (v !== undefined) headers.set(k, Array.isArray(v) ? v.join(", ") : v);`,
      `    const hasBody = req.method !== "GET" && req.method !== "HEAD";`,
      `    const request = new Request(url, { method: req.method, headers, ...(hasBody ? { body: Readable.toWeb(req) as unknown as ReadableStream, duplex: "half" } : {}) } as RequestInit);`,
      `    const info = { remoteAddr: { transport: "tcp", hostname: req.socket.remoteAddress ?? "0.0.0.0", port: req.socket.remotePort ?? 0 } };`,
      `    const response = typeof handler === "function" ? await handler(request, info) : await handler.fetch(request);`,
      `    res.writeHead(response.status, Object.fromEntries(response.headers));`,
      `    if (response.body) Readable.fromWeb(response.body as never).pipe(res);`,
      `    else res.end();`,
      `  } catch (err) {`,
      `    console.error(err);`,
      `    res.writeHead(500).end("Internal Server Error");`,
      `  }`,
      `}).listen(port, () => console.log(\`listening on http://localhost:\${port}\`));`,
      ``,
    );
  } else if (!jobs.length) {
    L.push("// No entry points were detected.", "");
  }
  if (jobs.length) {
    L.push(`type Job = { name: string; schedule: string | undefined; run: (c: { scheduledTime: number }) => unknown };`, `const jobs: Job[] = [`, ...jobs.map((j) => `  ${j.expr.replace(/\(c: ScheduledController\)/g, "(c: { scheduledTime: number })")},`), `];`, `for (const job of jobs) {`, `  if (!job.schedule) { console.warn(\`Skipping \${job.name}: no schedule configured\`); continue; }`, `  new Cron(job.schedule, { timezone: "UTC", protect: true }, async () => {`, `    try { await job.run({ scheduledTime: Date.now() }); } catch (err) { console.error(job.name, err); }`, `  });`, `}`, "");
  }
  return { text: L.join("\n"), warnings };
}

const KV_EXPORT = `// Deno script: dumps a Deno KV database into \`wrangler kv bulk put\` files, using the same key encoding the
// converted Worker uses (src/exit-ramp/kv-codec.ts). Run it with Deno, against a copy of your data:
//
//   deno run --allow-read --allow-write --unstable-kv migrate/deno-kv-export.ts [path-or-url]
//   npx wrangler kv bulk put kv-bulk-0001.json --binding KV            # add --remote to write to the real namespace
//
// Not carried over: versionstamps, queues, and expiry times (Deno's list() does not expose them). Check counts after import.
import { toBulk } from "../src/exit-ramp/kv-codec.ts";

const kv = await Deno.openKv(Deno.args[0]);
const CHUNK = 10_000; // wrangler kv bulk put accepts at most 10,000 pairs per file
let batch: { key: Deno.KvKey; value: unknown }[] = [];
let n = 0;
let file = 0;
const flush = async () => {
  if (!batch.length) return;
  const name = \`kv-bulk-\${String(++file).padStart(4, "0")}.json\`;
  await Deno.writeTextFile(name, JSON.stringify(toBulk(batch)));
  console.log(\`wrote \${name} (\${batch.length} entries)\`);
  batch = [];
};
for await (const entry of kv.list({ prefix: [] })) {
  batch.push({ key: entry.key, value: entry.value });
  n++;
  if (batch.length >= CHUNK) await flush();
}
await flush();
console.log(\`exported \${n} entries\`);
kv.close();
`;

export function scaffold(i: ScaffoldInput): { files: OutputFile[]; warnings: string[] } {
  const files: OutputFile[] = [];
  const add = (path: string, content: string) => files.push({ path, content });
  const w = workerTs(i);
  const b = i.bindings;
  const workers = i.target === "workers";
  if (workers) add("wrangler.toml", wranglerToml(i));
  add("package.json", packageJson(i));
  add("tsconfig.json", tsconfigJson(i.target));
  add(".gitignore", ["node_modules", ".wrangler", ".dev.vars", ".env", "dist", "kv-bulk-*.json", ""].join("\n"));
  add(workers ? ".dev.vars.example" : ".env.example", devVarsExample(i));
  if (b.jsr) add(".npmrc", "@jsr:registry=https://npm.jsr.io\n");
  add(workers ? "src/worker.ts" : "src/server.ts", w.text);
  if (workers) {
    add("src/env.d.ts", envDts(i));
    if (b.valtownTypes.interval || b.valtownTypes.email) add("src/valtown-types.d.ts", valtownTypesDts(b));
    const helper = (n: string) => add(`src/exit-ramp/${n}.ts`, TEMPLATES[n]);
    if (b.kv) {
      helper("kv");
      helper("kv-codec");
      add("migrate/deno-kv-export.ts", KV_EXPORT);
    }
    if (b.d1) helper("sqlite");
    if (b.r2) helper("blob");
    if (b.email) helper("email");
    if (b.emailIn) helper("email-in");
    if (b.lastRun) helper("last-run");
  }
  return { files, warnings: w.warnings };
}

export function dependencyFromJsr(name: string, range: string): Dependency {
  return jsrToNpmAlias(name, range);
}
